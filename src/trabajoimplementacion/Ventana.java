    private void lexico(){
        Reader reader;
        Lexer lexer;
        String resultados;
        try{
            reader = new BufferedReader(new StringReader(txtCodigo.getText()));
            lexer = new Lexer(reader);
            resultados = "";
            while(true){
                Tokens tokens = lexer.yylex();
                if(tokens==null){
                    resultados = resultados+"FIN";
                    txtLexico.setText(resultados);
                    return;
                }
                switch(tokens) {
                    case ERROR: 
                        resultados = resultados + "NO_DEFINIDO\n";
                        break;
                    case CadenaTexto:
                    case Identificador:
                    case Numero:
                    case NumeroDecimal:
                    case Coma:
                    case PuntoComa:
                    case ParentesisAbierto:
                    case ParentesisCerrado:
                    case Color:
                    case SetForma:
                    case Velocidad:
                    case Direccion:
                    case Avanzar:
                    case Retroceder:
                    case Girar:
                    case Detener:
                    case Sensor:
                    case Sonido:
                    case Carrito:
                    case Espacio:
                    case SetEspacio:
                    case Igual:
                    case Suma:
                    case Resta:
                    case Multiplicacion:
                    case Division:
                    case Punto:
                        resultados = resultados + "[ " + lexer.lexeme + "  :  " + tokens + " ]\n";
                        break;
                    default:
                        resultados = resultados + "[ Token: " + tokens + " ]\n";
                        break;
                }
            }
        } catch (FileNotFoundException ex){
        } catch (IOException ex){
        }
        catch (NullPointerException ex){
            System.out.println("No selecciono archivo");
        }
    }
    
    private void sintactico(){
        String cadena = txtCodigo.getText().replace("\r\n", "\n").replace('\r', '\n');
        Syntactic sintactico = new Syntactic(new LexerCup(new StringReader(cadena)));
        try{
            sintactico.parse();
            txtSintactico.setText("ANÁLISIS EXITOSO SIN ERRORES.");
            txtSintactico.setForeground(Color.BLUE);
        } catch (Exception ex){
            Symbol simbolo = sintactico.getS();
            txtSintactico.setText(
                "ERROR ENCONTRADO:" +
                "\n- Línea: " + (simbolo.left + 1) + 
                "\n- Columna: " + (simbolo.right) + 
                "\n- Valor: [ " + simbolo.value + " ]"
            );
            txtSintactico.setForeground(Color.RED);
        }
    }
